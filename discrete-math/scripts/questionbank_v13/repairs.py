def repair(q, point):
    old = q['prompt']
    key = point.removeprefix('DM-K')
    if q['id'] in OVERRIDES:
        result = OVERRIDES[q['id']]
    elif not q.get('meta', {}).get('generator'):
        result = CONTEXT[key]+'\n\n'+old
        if q['id']=='DM-V10-04-02':
            result='设 P 为二元谓词，x、y 为变量，z 为未使用的新变元。对公式 ∀x(P(x,y)) 中的自由变量 y 用项 x 替换。为避免代入的 x 被量词捕获，应如何处理？'
    else:
        p=q['meta']['parameters']; ch=int(key[:2]); topic=int(key[3:])
        result=old
        if ch==1:
            result='本题使用二值命题逻辑，1 表示真、0 表示假。\n\n'+old
            if '⊕' in old: result='⊕ 表示两个真值恰好一个为真的异或。\n\n'+result
            if '↔' in old: result='↔ 表示两个命题真值相同的双条件。\n\n'+result
        elif ch==2 and topic==1:
            result='¬、∧、∨ 分别表示否定、合取、析取，括号内各数字比较按通常整数次序判断。\n\n'+old
        elif ch==2:
            rows='{'+','.join('('+','.join(map(str,row))+')' for row in p['rows'])+'}'
            context=f'设 F(p,q,r) 为三原子命题公式，真值 1 表示真、0 表示假。按 (p,q,r) 顺序，恰使 F 为真的赋值为 {rows}，其余赋值均使 F 为假。'
            if 'assignment' in p:
                a='('+','.join(map(str,p['assignment']))+')'
                result=context+f'\n\n赋值 {a} 对应的极小项应选入 F 的主析取范式。这个判断是否成立？'
            else:result=context+'\n\nF 的主析取范式共包含多少个不同极小项？'
        elif ch==3:result='p、q 为任意命题，各前提需在同一真值赋值下同时为真，→ 为蕴涵。\n\n'+old
        elif ch==4 and topic==2:
            formula=p['formula']
            formula=re.sub(r'([∀∃][a-z])\s*([PQR]\([a-z,]+\))',r'\1(\2)',formula)
            result='本题只判断变量绑定：P、Q、R 是题中所需元数的谓词符号，小写字母为变量。每个量词只约束其紧随的子公式；括号明确辖域。'+f'\n\n在公式 {formula} 中，变量 {p["candidate"]} 存在自由出现。是否成立？'
        elif ch in (4,5):result='所有量词只在题目给定的个体域内取值，关系或性质均按题设定义。\n\n'+old
        elif ch==7:
            if topic==1 and 'x' in p:result='x、y 为实数，有序对相等要求对应坐标分别相等。\n\n'+old
            elif topic in (3,4,5,6) and 'A=' not in old:result='R、S（如出现）均为 A={1,2,3} 上的关系；有序对的两个坐标保持顺序。\n\n'+old
            else:result='本题的 R 为所给集合上的关系，∅ 为不含任何有序对的空关系。\n\n'+old if topic in (2,3,4,5,6) else old
        elif ch==8:result='函数从题设声明的定义域映射到声明的陪域；列表按输入 1、2、… 的次序给出每个函数值。\n\n'+old if 'outputs' in p else old
        elif ch==9:result='mod 表示按题设模数取最小非负余数，运算结果使用该代表元。\n\n'+old
        elif ch==10 and topic==1 and 'x' in p:
            mod=p['mod'];x=p['x'];result=f'Z_{mod}={{0,1,…,{mod-1}}}，运算是模 {mod} 加法，单位元为 0。元素的阶是使反复相加返回 0 的最小正次数。\n\n元素 {x} 的阶是多少？'
        elif ch==10:result='本题的群阶为元素数量；所列有限群及运算以题目声明为准。\n\n'+old
        elif ch==13 and topic==1:
            v=p['values'];idx=p['idx']
            if p['first_order']:result=f'设实数序列 a₀={v[0]}，对每个整数 n≥1，递推式为 aₙ={p["c"]}aₙ₋₁+{p["d"]}。\n\n求 a_{idx}。'
            else:result=f'设实数序列 a₀={v[0]}、a₁={v[1]}，对每个整数 n≥2，递推式为 aₙ=aₙ₋₁+aₙ₋₂。\n\n求 a_{idx}。'
        elif ch==13:
            a=p['a'];idx=p['idx'];function=f'1/(1−{a}x)' if p['geometric'] else f'1/(1−x)^{a}'
            result=f'普通生成函数 A(x)={function}，按从 x⁰ 开始的形式幂级数展开为 A(x)=Σ_(n≥0)a_nxⁿ。\n\n求 x^{idx} 的系数 a_{idx}。'
        elif ch in (14,15,16,18) and ('edges' in p or 'weighted' in p):
            result='这是有限简单无向图。边 (u,v) 仅表示无向边的两个端点；除题中列出的边外没有其他边。\n\n'+old
        elif ch==19:
            result=('在整数范围内，gcd 是非负最大公约数。\n\n' if topic==1 else '在整数范围内，mod m 的标准结果为 0≤r<m 的唯一余数。\n\n')+old
    assert not re.search(r'同样的|同上一题|如图|上题|上述关系|前述集合',result), q['id']
    q['prompt']=result
    if q['kind']=='choice':
        full_answer=q['answer']['text'].split('. ',1)[1]
        if full_answer not in q['answer']['accepted']:
            q['answer']['accepted'].append(full_answer)
    q['meta']['full_statement_version']=13
    q['meta']['statement_review']='对象、范围、符号及独立作答所需条件已核对'
    if q['source_type']=='textbook':q['meta']['statement_note']='按已核验题意补足上下文；保留教材来源编号，非逐字重引'
    return old!=result
