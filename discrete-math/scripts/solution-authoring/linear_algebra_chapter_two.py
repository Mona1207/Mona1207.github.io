def multiply(A,B,label):
 assert A.cols==B.rows
 C=A*B
 out=[f'**{label}。** 左矩阵为{A.rows}×{A.cols}，右矩阵为{B.rows}×{B.cols}，内维数相同，可乘；结果为{C.rows}×{C.cols}。每个元素按左边第i行与右边第j列点乘。']
 for i in range(C.rows):
  equations=[]
  for j in range(C.cols):
   terms='+'.join('('+L(A[i,k])+')('+L(B[k,j])+')' for k in range(A.cols))
   equations.append('c_{'+str(i+1)+str(j+1)+'}='+terms+'='+L(sp.expand(C[i,j])))
  out.append('结果第'+str(i+1)+'行逐项计算：$$'+r'\begin{aligned}'+r'\\'.join(equations)+r'\end{aligned}$$')
 out.append('将上述各元素按原行列位置排好：$$'+label+'='+L(C)+'.$$')
 return out

def solve_left_right(A,C,B,label):
 assert A.rows==A.cols and B.rows==B.cols and A.det()!=0 and B.det()!=0
 out=[fr'**{label}。** 方程为 $AXB=C$，$\det A='+L(A.det())+r'\ne0,\det B='+L(B.det())+r'\ne0$。左乘A的逆、右乘B的逆，保持顺序得 $X=A^{-1}CB^{-1}$。']
 out+=['先计算左系数矩阵A的逆。']+inverse(A)[0]
 out+=['再计算右系数矩阵B的逆。']+inverse(B)[0]
 out+=multiply(A.inv(),C,r'A^{-1}C')+multiply(A.inv()*C,B.inv(),r'X')
 X=A.inv()*C*B.inv();assert A*X*B==C
 out+=['反代核验：$$AXB='+L(A*X*B)+'=C.$$因左右系数都可逆，解唯一。']
 return out

def cramer_and_inverse(A,b,label):
 assert A.rows==A.cols and A.det()!=0
 out=[f'**{label}：先用克拉默法则。** 系数矩阵 $A='+L(A)+r'$，常数列 $b='+L(b)+r'$。先完整展开系数行列式。']+determinant(A)
 D=A.det();replaced=[]
 for j in range(A.cols):
  M=A.copy();M[:,j]=b;replaced.append(M.det())
  out+=['只将第'+str(j+1)+'列替换为b，得到 $$A_{'+str(j+1)+'}='+L(M)+'.$$']+determinant(M)
 x=sp.Matrix([v/D for v in replaced]);assert A*x==b
 out+=['系数行列式非0，因此 $$x='+L(x)+r',\qquad x_i=\det A_i/\det A.$$']
 out+=['**再用逆矩阵法。** 将同一A与单位阵并排进行行变换。']+inverse(A)[0]
 out+=multiply(A.inv(),b,'x')
 out+=['两种方法所得解相同，反代 $$Ax='+L(A*x)+'=b.$$']
 return out

