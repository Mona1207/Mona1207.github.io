def row_work(A,label,transform=False):
 B,ops,rank=reduce(A,transform)
 out=[f'**{label}。** 从矩阵 $$'+L(A)+r'$$出发，只作可逆初等行变换：交换两行、某行乘非零数、某行加另一行的倍数。']
 if transform:out+=['为记录可逆左乘矩阵，在右侧接同阶单位阵：$$'+L(A.row_join(sp.eye(A.rows)))+'.$$']
 out+=['作 $'+op+'$，得到 $$'+L(M)+'.$$' for op,M in ops]
 F=B[:,:A.cols]
 assert F==A.rref()[0] and rank==A.rank()
 out+=['所得行最简形为 $$F='+L(F)+r'.$$各非零行首项为1，主元列其余全0，零行置底；共有'+str(rank)+'个主元，所以秩为'+str(rank)+'。']
 if transform:
  P=B[:,A.cols:];assert P*A==F and P.det()!=0
  out+=['同样变换把右侧单位阵变成 $$P='+L(P)+r',\quad\det P='+L(P.det())+r'\ne0.$$于是PA=F。P是初等矩阵的乘积，故可逆；满足条件的P可以不唯一。']
 return out

def system(A,b,label):
 assert b.cols==1 and b.rows==A.rows
 M=A.row_join(b);F,ops,_=reduce(M);r=A.rank();ra=M.rank();n=A.cols
 out=[f'**{label}。** 未知数按x₁至x'+str(n)+r'排列，建立增广矩阵 $$(A\mid b)='+L(M)+'.$$每次行变换同时作用于常数列。']
 out+=['作 $'+op+'$，得到 $$'+L(N)+'.$$' for op,N in ops]
 if r!=ra:
  row=next(i for i in range(F.rows) if all(F[i,j]==0 for j in range(n)) and F[i,n]!=0)
  out+=['第'+str(row+1)+'行的未知数系数全0、常数为'+L(F[row,n])+r'，即 $0='+L(F[row,n])+r'$，矛盾。因此无解。$R(A)='+str(r)+r'<R(A\mid b)='+str(ra)+'$，没有“选自由参数”可以消除该矛盾。']
  return out
 pivots=list(A.rref()[1]);free=[j for j in range(n) if j not in pivots]
 params=sp.symbols('t_1:'+str(len(free)+1)) if free else []
 x=sp.zeros(n,1)
 for j,t in zip(free,params):x[j]=t
 for i,j in enumerate(pivots):x[j]=sp.simplify(F[i,n]-sum(F[i,k]*x[k] for k in free))
 assert A*x==b
 out+=['系数秩与增广秩均为'+str(r)+'，所以有解。未知数'+str(n)+'个，自由变量有'+str(n-r)+'个。'+('秩等于未知数数目，解唯一。' if not free else '取非主元列对应变量为任意实参数，其余变量由主元行唯一决定。')]
 if free:out+=['指定 $$'+r',\quad '.join('x_{'+str(j+1)+'}='+L(t) for j,t in zip(free,params))+r',\quad t_i\in\mathbb R.$$']
 out+=['逐主元行解出：$$'+r'\begin{aligned}'+r'\\'.join('x_{'+str(j+1)+'}='+L(x[j]) for j in pivots)+r'\end{aligned}$$']
 xp=x.subs({t:0 for t in params});basis=[x.diff(t) for t in params]
 expression=L(xp)+''.join('+'+L(t)+L(v) for t,v in zip(params,basis))
 out+=['所以完整通解为 $$x='+expression+r'.$$等价分量列式是 $$x='+L(x)+'.$$']
 assert A*xp==b and all(A*v==sp.zeros(A.rows,1) for v in basis)
 out+=['反代：特解满足 $$Ax_0='+L(A*xp)+r'=b$$，每个参数方向vᵢ都满足Avᵢ=0。自由变量已全部任选，主元变量全部由行最简形给出，所以没有漏解；同一参数式中重复使用的是同一个参数。']
 return out

def matrix_equation(A,B,label):
 assert A.rows==A.cols and A.det()!=0
 F,ops,_=reduce(A.row_join(B));X=F[:,A.cols:];assert A*X==B
 out=[f'**{label}。** 将所有右端列一并接到A右侧：$$'+L(A.row_join(B))+r'.$$A可逆，统一行变换能同时解各右端列，不可各列使用不一致的行操作。']
 out+=['作 $'+op+'$，得到 $$'+L(M)+'.$$' for op,M in ops]
 out+=['左块化为单位阵，故 $$X='+L(X)+r'.$$反代 $$AX='+L(A*X)+r'=B$$，解唯一。']
 return out

