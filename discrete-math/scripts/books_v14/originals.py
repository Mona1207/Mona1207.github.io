def tex(A):return r'\begin{pmatrix}'+r'\\'.join('&'.join(str(x) for x in row) for row in A)+r'\end{pmatrix}'
def reduce(A):
 a=[[F(x) for x in row] for row in A];steps=[];r=0
 for c in range(len(a[0])):
  k=next((i for i in range(r,len(a)) if a[i][c]),None)
  if k is None:continue
  if k!=r:a[r],a[k]=a[k],a[r];steps.append(f'交换第 {r+1} 行与第 {k+1} 行。')
  v=a[r][c]
  if v!=1:a[r]=[x/v for x in a[r]];steps.append(f'第 {r+1} 行除以 {v}，把主元化为 1。')
  for i in range(len(a)):
   if i==r or not a[i][c]:continue
   v=a[i][c];a[i]=[x-v*y for x,y in zip(a[i],a[r])];steps.append(f'第 {i+1} 行减去第 {r+1} 行的 {v} 倍，消去该列元素。')
  r+=1
  if r==len(a):break
 return a,steps

