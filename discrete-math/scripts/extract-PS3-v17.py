def sources():
    out=[x for f in sorted((REPO/'discrete-math/data').glob('originals-PS3-v15-*.json')) for x in json.loads(f.read_text())['items'] if x['kind']=='example']
    return sorted(out,key=lambda x:(x['pdf_page'],x['segments'][0]['top']))

def regions(item):
    segs=sorted(item['segments']+item.get('answer_segments',[]),key=lambda x:(x['page'],x['top']))
    merged=[]
    for s in segs:
        if merged and merged[-1]['page']==s['page'] and s['top']<=merged[-1]['bottom']+.02:
            merged[-1]['bottom']=max(merged[-1]['bottom'],s['bottom'])
        else: merged.append(dict(s))
    return merged

def lowres(seg):
    lines=collections.OrderedDict()
    raw=(OCR/f"{seg['page']:03}.tsv").read_text().splitlines()
    h=int(raw[1].split('\t')[9])
    for row in raw[2:]:
        p=row.split('\t',11)
        if len(p)<12 or p[0]!='5': continue
        if seg['top']-.003 <=(int(p[7])+int(p[9])/2)/h <=seg['bottom']+.003:
            lines.setdefault(tuple(p[2:5]),[]).append(p[11])
    return '\n'.join(''.join(t) for t in lines.values())

def ocr(item):
    target=CACHE/f"{item['id']}.txt"
    if target.exists(): return item['id'],'cached'
    d=fitz.open(SOURCE);parts=[]
    for n,s in enumerate(regions(item)):
        pg=d[s['page']-1];r=pg.rect
        clip=fitz.Rect(r.width*.055,max(0,r.height*s['top']-3),r.width*.97,min(r.height,r.height*s['bottom']+3))
        img=CACHE/f"{item['id']}-{n}.png";base=img.with_suffix('')
        pg.get_pixmap(dpi=300,clip=clip).save(img)
        z=subprocess.run(['tesseract',str(img),str(base),'--tessdata-dir',str(ROOT/'ocr-models'),'-l','chi_sim','--psm','3'],capture_output=True,text=True)
        if z.returncode: raise RuntimeError(z.stderr)
        parts.append(base.with_suffix('.txt').read_text().strip())
        # Keep image available for targeted visual review while work is in progress.
    target.write_text('\n\n'.join(parts))
    return item['id'],'ocr'

